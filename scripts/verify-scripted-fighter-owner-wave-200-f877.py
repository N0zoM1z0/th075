    zero=ld('f877zero','verify-fighter-actionzero-natural-source.py')
    sw=ld('f877sw','verify-fighter-natural-switch-probes.py')
    pe=rd.verified_target();d=Cs(CS_ARCH_X86,CS_MODE_32)
