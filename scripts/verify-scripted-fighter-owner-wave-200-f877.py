def need(v,msg):
    if not v:raise ValueError(msg)
def ld(tag,name):
    sp=importlib.util.spec_from_file_location(tag,R/'scripts'/name)
    need(sp is not None and sp.loader is not None,'original PE helper missing '+name)
    m=importlib.util.module_from_spec(sp);sys.modules[tag]=m;sp.loader.exec_module(m);return m

def source():
    O.mkdir(parents=True,exist_ok=True)
    prev=R/'.analysis/f875-scripted-owner-stages/Boss005214B0-F875-whole.cpp'
    receipt=R/'.analysis/f875-scripted-owner-stages/verified-summary.json'
    if not prev.exists() or not receipt.exists():
        run=subprocess.run([str(R/'scripts/repo-python'),
              str(R/'scripts/verify-scripted-fighter-owner-stages-1ff-f875.py')],
              cwd=R,capture_output=True,text=True,timeout=1400)
        (O/'f875-fallback-original.log').write_text(run.stdout+run.stderr)
        need(run.returncode==0,'prior F875 original source missing '+(run.stdout+run.stderr)[-680:])
    old=json.loads(receipt.read_text())
    need(old['new_generated_whole_source_CODE_B']==31378
         and old['whole_original_game_exact'] is False,
         'prior original 1FF whole PE evidence receipt changed')
    cpp=prev.read_text()
    marker='        case 0x200: g_FighterProbeMarker = 513; break;'
    inc=(R/'probes/FighterScriptedOwnerWave200F877.inc').read_text()
    need(cpp.count(marker)==1 and inc.count('case 0x200:')==1
         and inc.count('return;')==2
         and inc.count('SetNativeActionAt40FAC0(0x64);')==6
         and inc.count('OWNER+0x44')==6
         and 'reinterpret_cast<FighterBorrowedXViewF833*>(this)->xAt44-float' in inc
         and '*reinterpret_cast<char*>(OWNER+0x66)=*reinterpret_cast<char*>(RAW+0x66)' in inc
         and 'SetNativeActionAt40FAC0(0x35)' in inc,
         'real native owner 200 C++ stage4 facing and stage5 FSUBR source changed')
    return cpp.replace(marker,'#include "FighterScriptedOwnerWave200F877.inc"',1)

def compile_one(src,variant='whole'):
    cpp=O/('Boss005214B0-F877-'+variant+'.cpp')
    obj=O/('Boss005214B0-F877-'+variant+'.obj')
    cpp.write_text(src)
    E=os.environ.copy();E.pop('DISPLAY',None);E.pop('WAYLAND_DISPLAY',None)
    E['WINEPREFIX']=str(R/'.analysis/vc71-wine')
    E['WINEDLLOVERRIDES']='winex11.drv,winewayland.drv,winemac.drv=d;winemenubuilder.exe=d'
    p=subprocess.run([str(R/'scripts/compile-probe.sh'),str(cpp),str(obj),
        '/Od','/Ob0','/Gy','/GR-','/GX-','/GS','/Zi','/I','src','/I','probes'],
        cwd=R,env=E,capture_output=True,text=True,timeout=320)
    (O/('compiler-'+variant+'.log')).write_text(p.stdout+p.stderr)
    need(p.returncode==0,'whole VC7.1 native original 200 '+variant+' build failed '+(p.stdout+p.stderr)[-740:])
    return obj

def main():
    rd=ld('f877rd','compare-coff-function.py')
    ac=ld('f877ac','report-fighter-action-handlers.py')
    f834=ld('f877f834','verify-scripted-fighter-fourway-c8-f834.py')
