    need(len(old)==46 and old[0]['case']=='0xc8' and old[-1]['case']=='0x1fc',
         'earlier 46 reviewed physical case entries missing')
    beginning=I[k-177-(107+107+149)-sum(x['native_complete_x86'] for x in old):k-177-(107+107+149)]
