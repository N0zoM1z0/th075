    need((ret,len(I),len(refs),len(code)-ret)==(31997,8974,1111,901)
         and I[3].op_str=='dword ptr [ebp - 0x10], ecx',
         'whole normal original 200 fighter VC7.1 x86/ABI/COFF changed')
