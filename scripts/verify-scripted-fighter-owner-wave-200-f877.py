    need(fragment.count(correct)==1,'real borrowed float X source expression changed')
    bad_fragment=fragment.replace(correct,incorrect,1)
    need(src.count('#include "FighterScriptedOwnerWave200F877.inc"')==1,
         'new source include cannot be replaced in native negative control')
    wrong_src=src.replace('#include "FighterScriptedOwnerWave200F877.inc"',bad_fragment,1)
    bad_obj=compile_one(wrong_src,variant='wrong-fisub-control')
    bad_code,bad_refs=rd.object_function(bad_obj,SYM)
