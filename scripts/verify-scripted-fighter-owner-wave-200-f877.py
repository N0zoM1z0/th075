    need(offsets==OFFSETS and len(BAD)==135 and BAD[-2:]==[630,631],
         'original 200 native PE fields or honest GPR/JMP negative list changed')
    scratches=[]
    for ordinal,slot in zip(SCRATCH_ORDINALS,SCRATCH_MINUS):
        orig,cur=original[ordinal],now[ordinal]
        # Real compiler uses each observed integer slot as FILD source
        # immediately after its real store, without inert locals.
        need(orig.mnemonic==cur.mnemonic=='mov'
             and orig.size==cur.size
             and orig.op_str.startswith(f'dword ptr [ebp - 0x{slot:x}],')
             and cur.op_str.startswith(f'dword ptr [ebp - 0x{slot:x}],')
             and original[ordinal+1].mnemonic==now[ordinal+1].mnemonic=='fild',
             'F877 original FILD integer source stack slot changed '+hex(slot))
        scratches.append(f'-0x{slot:x}')
    need(original[160].mnemonic==now[160].mnemonic=='fsubr'
         and original[160].size==now[160].size==3,
         'real x87 last stage must FILD then FSUBR observed member +0x44')
    # Recompile real but wrong plain subtraction as whole function.
    # It yields a FLOAT - INTEGER expression with a FISUB
    # rather than the native integer FILD then FSUBR.
    fragment=(R/'probes/FighterScriptedOwnerWave200F877.inc').read_text()
    correct='reinterpret_cast<FighterBorrowedXViewF833*>(this)->xAt44-float((*reinterpret_cast<signed char*>(RAW+0x66))*26)'
