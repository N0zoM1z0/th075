#!/usr/bin/env python3
"""F1038: complete 82KB fighter F1024 typed animation stage/phase borrow.

Construct the genuine previous source spelling from the tracked typed probe,
compile BOTH complete parents with pinned VC7.1, and inspect actual original
Japanese PE against every whole CODE instruction + afterRET data. Only local
COFF `$L` numbers may change; physical binding and generated bytes must not.
"""
from pathlib import Path
from capstone import Cs,CS_ARCH_X86,CS_MODE_32
import importlib.util,json,os,re,subprocess,sys
R=Path(__file__).resolve().parents[1]
O=R/'.analysis/f1038-third-phase';O.mkdir(parents=True,exist_ok=True)
typed=(R/'probes/FighterWhole004AC040F1020.cpp').read_text()
HEADER='#include "FighterAnimationPhaseBorrowedF1024.hpp"\n'
assert typed.count(HEADER)==1
old=typed.replace(HEADER,'',1)
patterns={'F1024_PHASE(this).stageAt62':'S16(0x62)',
          'F1024_PHASE(this).frameAt64':'S16(0x64)'}
for oldtext,newtext in patterns.items():
 assert typed.count(oldtext)>10,(oldtext,typed.count(oldtext))
 old=old.replace(oldtext,newtext)
# The single older early case 0xA source spelling used the alternate I16 macro.
late='if (S16(0x62) == 0 && S16(0x64) == 0)\n                PrepareActionAt453D60(30);'
assert old.count(late)==1
old=old.replace(late,'if (I16(0x62) == 0 && I16(0x64) == 0)\n                PrepareActionAt453D60(30);',1)
sp=importlib.util.spec_from_file_location('f1038reader',R/'scripts/compare-coff-function.py')
rd=importlib.util.module_from_spec(sp);sys.modules[sp.name]=rd;sp.loader.exec_module(rd)
D=Cs(CS_ARCH_X86,CS_MODE_32);PE=rd.verified_target();BASE=0x4ac040;SIZE=82796;DATA=1126
native=list(D.disasm(rd.pe_bytes_at(PE,BASE,SIZE),BASE))
assert len(native)==22721 and native[2].op_str=='esp, 0x720'
after=rd.pe_bytes_at(PE,BASE+SIZE,DATA)
REG=re.compile(r'\b(?:[er]?(?:ax|bx|cx|dx|si|di|sp|bp)|[abcd]h|[abcd]l)\b')
roles=lambda x:tuple(REG.findall(x.op_str))
E=os.environ.copy();E.pop('DISPLAY',None);E.pop('WAYLAND_DISPLAY',None)
E['WINEPREFIX']=str(R/'.analysis/vc71-wine');E['WINEDLLOVERRIDES']='winex11.drv,winewayland.drv,winemac.drv=d;winemenubuilder.exe=d'
rows={};objects={}
for tag,source in [('plain-original-spelling',old),('tracked-typed-phase',typed)]:
 cpp=O/(tag+'.cpp');obj=O/(tag+'.obj');cpp.write_text(source)
 cp=subprocess.run([str(R/'scripts/compile-probe.sh'),str(cpp),str(obj),
 '/Od','/Ob0','/Gy','/GR-','/GX','/GS','/Zi','/I','src','/I','probes'],
 cwd=R,env=E,capture_output=True,text=True,timeout=360)
 (O/(tag+'.log')).write_text(cp.stdout+cp.stderr)
 assert cp.returncode==0,(tag,(cp.stdout+cp.stderr)[-900:])
 code,refs=rd.object_function(obj,'?Advance@FighterSwitchF598_Boss004AC040@@QAEXXZ')
 I=[]
 for inst in D.disasm(code,0):
  I.append(inst)
  if inst.mnemonic=='ret':break
 end=I[-1].address+I[-1].size
 assert (end,len(I),len(code)-end)==(SIZE,22721,DATA)
 table=[r for r in refs if r['offset']>=end]
 assert len(table)==151
 labels={};mask=set()
 for r in table:
  j=r['offset']-end
  assert r['type']=='DIR32' and r['addend']==0 and r['local_symbol_offset'] is not None
  assert all(k not in mask for k in range(j,j+4))
  mask.update(range(j,j+4))
  original_target=int.from_bytes(after[j:j+4],'little')
  assert BASE<=original_target<BASE+SIZE
  labels.setdefault(original_target,r['local_symbol_offset'])
 assert len(mask)==151*4 and all(code[end+k]==after[k] for k in range(DATA) if k not in mask)
 m=[j for j,(n,s) in enumerate(zip(native,I)) if n.mnemonic!=s.mnemonic]
 w=[j for j,(n,s) in enumerate(zip(native,I)) if n.size!=s.size]
 g=[j for j,(n,s) in enumerate(zip(native,I)) if roles(n)!=roles(s)]
 assert m==[] and len(w)==12 and len(g)==6958
 assert I[2].op_str==native[2].op_str and I[4].op_str==native[4].op_str
 states={}
 for key,start,stop,nx,nf in [('58',0x4add25,0x4adefa,135,17),('59',0x4adefa,0x4ae05e,95,16)]:
  lo,hi=labels[start],labels[stop]
  region=[x for x in I if lo<=x.address<hi]
  original_region=[x for x in native if start<=x.address<stop]
  assert len(region)==len(original_region)==nx and (hi-lo)==stop-start
  refs_in=[r for r in refs if lo<=r['offset']<hi]
  assert len(refs_in)==nf
  for ref in refs_in:
   j=next(j for j,x in enumerate(region) if x.address<=ref['offset']<x.address+x.size)
   assert region[j].size==original_region[j].size and region[j].mnemonic==original_region[j].mnemonic
   delta=ref['offset']-region[j].address
   original_field=original_region[j].address+delta
   v=int.from_bytes(rd.pe_bytes_at(PE,original_field,4),'little',signed=ref['type']=='REL32')
   real_target=original_field+4+v if ref['type']=='REL32' else v
   match=re.search(r'At([0-9A-Fa-f]{6,8})',ref['symbol'])
   expected=int(match.group(1),16) if match else 0x6406ac if ref['symbol']=='__ftol2' else None
   assert ref['type'] in ('DIR32','REL32') and ref['addend']==0 and ref['local_symbol_offset'] is None
   assert expected==real_target,(tag,key,ref['symbol'],hex(real_target),expected)
  states[key]={'CODE_B':hi-lo,'x86':nx,'native_PE_fields_verified':len(refs_in),
   'wrong_mnemonics':sum(n.mnemonic!=s.mnemonic for n,s in zip(original_region,region)),
   'wrong_widths':sum(n.size!=s.size for n,s in zip(original_region,region)),
   'wrong_GPR_roles':sum(roles(n)!=roles(s) for n,s in zip(original_region,region))}
 row={'whole_source_CODE_B':end,'source_x86':len(I),'whole_original_GAME_CODE_B':SIZE,
 'whole_wrong_mnemonics':len(m),'whole_wrong_widths':len(w),'whole_wrong_GPR':len(g),
 'afterRET_native_DIR32':len(table),'afterRET_native_literal_equal_B':DATA-len(mask),
 'native_cases':states,'nonexact_original_whole':True}
 objects[tag]=(code,refs);rows[tag]=row
 print(tag,'whole',end,len(I),'native M/W/G',len(m),len(w),len(g),
 'native 58 GPR',states['58']['wrong_GPR_roles'],'native 59 GPR',states['59']['wrong_GPR_roles'],flush=True)
plain,refplain=objects['plain-original-spelling'];now,refnow=objects['tracked-typed-phase']
assert now==plain, 'complete generated original-shaped function differs after typing'
assert len(refnow)==len(refplain)
changed=[]
for k,(a,b) in enumerate(zip(refnow,refplain)):
 if a!=b:
  assert all(a[f]==b[f] for f in ('offset','type_id','type','addend','local_symbol_offset'))
  assert a['local_symbol_offset'] is not None and re.fullmatch(r'\$L\d+',a['symbol']) and re.fullmatch(r'\$L\d+',b['symbol'])
  changed.append(k)
assert len(changed)==161,(len(changed),changed[:12])
summary={'selected_original_th075_game':'0x004AC040','source_changed_counters':34,
 'whole_generated_CODE_and_afterRET_identical':True,'whole_native_already_NONEXACT':True,
 'COFF_original_physical_offset_kind_addend_dest_identical':True,
 'external_source_symbol_names_unchanged':True,
 'local_compiler_generated_label_number_changes':len(changed),
 'new_accepted_exact_original_GAME_CODE_B':0,'all_979_cold_replay':False,
 'rows':rows}
(O/'verified-summary.json').write_text(json.dumps(summary,indent=2)+'\n')
print('F1038 typed and old natural 82KB C++ parents emit bit-identical whole bytes; 161 synthetic $L label names renumber, their true physical field targets unchanged. Neither parent is exact.')
